def swc_to_graph(swc):
    G = nx.Graph()

    # 添加节点
    for _, row in swc.iterrows():
        G.add_node(row['n'], **row.to_dict())

    # 添加边（忽略 parent = -1）
    for _, row in swc.iterrows():
        n = row['n']
        p = row['parent']
        if p != -1:
            G.add_edge(n, p)

    return G


def graph_to_swc(G, root):
    visited = set()
    queue = [(root, -1)]
    out = []

    while queue:
        node, parent = queue.pop(0)
        attr = G.nodes[node].copy()

        attr['n'] = node
        attr['parent'] = parent
        out.append(attr)

        visited.add(node)

        for nb in G.neighbors(node):
            if nb not in visited:
                queue.append((nb, node))

    return pd.DataFrame(out)


def load_swc_as_graph(swc_file):
    swc = load_swc(swc_file)
    G = swc_to_graph(swc)
    return G


def save_graph_as_swc(G, root, output_file):
    swc = graph_to_swc(G, root)
    save_swc(swc, output_file)


