def is_valid_tree_swc(swc_df):
    """
    全面校验 SWC 文件，包含结构错误检查和生物学合理性警告。

    Returns:
        tuple: (is_valid (bool), messages (list))
        - is_valid: False 表示存在结构性硬伤，True 表示结构正常。
        - messages: 包含 Error 和 Warning 的详细文本列表。
    """
    messages = []

    # ==========================================
    # Part 1: 硬伤检查 (Structural Errors)
    # 任何一项失败都会直接返回 False
    # ==========================================

    # 1. 唯一根节点检查
    roots = swc_df[swc_df['parent'] == -1]
    # print(roots)
    if len(roots) != 1:
        messages.append(f"[Error] 根节点数量不为 1 (发现 {len(roots)} 个)")
        return False, messages

    root_row = roots.iloc[0]
    root_id = root_row['n']

    # 2. 节点编号唯一性
    if swc_df['n'].duplicated().any():
        dup_ids = swc_df[swc_df['n'].duplicated()]['n'].unique()
        messages.append(f"[Error] 存在重复的节点编号: {dup_ids[:5]}...")
        return False, messages

    # 3. 父节点引用有效性
    node_ids = set(swc_df['n'])
    parent_ids = set(swc_df['parent'])
    if not (parent_ids - {-1}).issubset(node_ids):
        missing = (parent_ids - {-1}) - node_ids
        messages.append(f"[Error] 父节点指向了不存在的 ID: {list(missing)[:5]}...")
        return False, messages

    # --- 构建图结构 (高性能版) ---
    graph = defaultdict(list)     # Parent -> Children
    nodes_map = {}                # ID -> (x, y, z, r, type) 方便后续计算

    # 使用 numpy 数组加速迭代
    data_matrix = swc_df[['n', 'type', 'x', 'y', 'z', 'r', 'parent']].values

    for row in data_matrix:
        n, t, x, y, z, r, p = row
        n, p, t = int(n), int(p), int(t)
        nodes_map[n] = {'pos': np.array([x, y, z]), 'r': r, 'type': t}
        if p != -1:
            graph[p].append(n)

    # 4. 连通性与环路检查 (DFS)
    visited = set()
    stack = [root_id]

    while stack:
        current = stack.pop()
        if current in visited:
            messages.append(f"[Error] 图中存在环或汇聚节点 (节点 {current})")
            return False, messages
        visited.add(current)

        if current in graph:
            for child in graph[current]:
                stack.append(child)

    if len(visited) != len(node_ids):
        messages.append(f"[Error] 图不连通 (共有 {len(node_ids)} 节点, 根节点只能到达 {len(visited)})")
        return False, messages

    # ==========================================
    # Part 2: 软伤检查 (Warnings)
    # 结构合法，但形态可能异常
    # ==========================================

    # # Warning 1: 根节点半径检查 (通常 Soma 半径最大)
    # root_r = nodes_map[root_id]['r']
    # max_r = swc_df['r'].max()
