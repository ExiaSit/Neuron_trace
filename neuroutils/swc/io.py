def load_swc(swc_file):
    if(swc_file.endswith(".swc")):
        swc = pd.read_csv(
            swc_file,
            sep=' ',
            header=None,
            comment='#',
            dtype={
                0: int,
                1: int,
                2: float,
                3: float,
                4: float,
                5: float,
                6: int
            }
        )

        swc.columns = ['n', 'type', 'x', 'y', 'z', 'r', 'parent']

        try:
            neuron_id = extract_neuron_id(swc_file)
        except Exception:
            neuron_id = "unknown"
        swc['neuron_id'] = neuron_id

    elif(swc_file.endswith(".eswc")):
        swc = pd.read_csv(
            swc_file,
            sep=' ',
            header=None,
            comment='#',
            dtype={
                0: int,
                1: int,
                2: float,
                3: float,
                4: float,
                5: float,
                6: int,
                7: int,
                8: int,
                9: int,
                10: int,
                11: float
            }
        )

        swc.columns = ['n', 'type', 'x', 'y', 'z', 'r', 'parent',
                       'seg_id', 'level', 'mode', 'timestamp', 'feature_value']

        try:
            neuron_id = extract_neuron_id(swc_file)
        except Exception:
            neuron_id = "unknown"
        swc['neuron_id'] = neuron_id

    return swc

def save_swc(swc, output_file):

    # 1. 只保留标准 SWC 列
    swc = swc[['n', 'type', 'x', 'y', 'z', 'r', 'parent']]

    # 2. 按 n 排序
    swc = swc.sort_values(by='n').reset_index(drop=True)

    # 3. 转换为正确的数据类型
    swc = swc.astype({
        'n': int,
        'type': int,
        'x': float,
        'y': float,
        'z': float,
        'r': float,
        'parent': int,
    })

    # 4. 写入 SWC 文件
    with open(output_file, 'w') as f:
        f.write('# Generated by Neuroutils\n')
        f.write('#\n')
        f.write('# id type x y z radius parent\n')
        swc.to_csv(f, sep=' ', index=False, header=False)

